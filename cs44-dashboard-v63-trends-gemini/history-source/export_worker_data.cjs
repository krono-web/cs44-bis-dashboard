"use strict";
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const root = path.resolve(__dirname, "../dashboard");
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, "data.js"), "utf8"), context);
vm.runInNewContext(fs.readFileSync(path.join(root, "history-data.js"), "utf8"), context);
const datasets = { original: context.window.CS44_DATA, ...context.window.CS44_HISTORY.years };
const output = path.resolve(__dirname, "../cloudflare-worker/datasets.json");
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, JSON.stringify(datasets));
console.log(`Wrote ${output} (${fs.statSync(output).size} bytes)`);
